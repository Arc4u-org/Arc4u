using System.Diagnostics.CodeAnalysis;
using System.Text.Json.Serialization.Metadata;
using Microsoft.Extensions.Configuration;

namespace Arc4u.Configuration.Store;

/// <summary>
/// Configuration options for persisted configuration sections
/// </summary>
public interface ISectionStoreConfigurationOptions
{
    /// <summary>
    /// Add a section with a specific value to be persisted
    /// </summary>
    /// <remarks>The value is serialized with reflection, which trimming and native AOT do not support: use <see cref="Add{TValue}(string, TValue, JsonTypeInfo{TValue})"/> there.</remarks>
    /// <typeparam name="TValue">The type of the value</typeparam>
    /// <param name="key">the name of the section</param>
    /// <param name="value">the value of the section</param>
    /// <returns></returns>
    [RequiresUnreferencedCode("The value is serialized with reflection. Use the overload taking a JsonTypeInfo<TValue>, generated by a JsonSerializerContext in your application.")]
    [RequiresDynamicCode("The value is serialized with reflection. Use the overload taking a JsonTypeInfo<TValue>, generated by a JsonSerializerContext in your application.")]
    ISectionStoreConfigurationOptions Add<TValue>(string key, TValue? value);

    /// <summary>
    /// Add a section with a specific value to be persisted, serialized with <paramref name="typeInfo"/>.
    /// Because the metadata is generated in the application, where <typeparamref name="TValue"/> is known, it works with trimming and native AOT.
    /// </summary>
    /// <typeparam name="TValue">The type of the value</typeparam>
    /// <param name="key">the name of the section</param>
    /// <param name="value">the value of the section</param>
    /// <param name="typeInfo">The Json metadata of <typeparamref name="TValue"/>, typically <c>MyJsonContext.Default.MyOptions</c>.</param>
    /// <returns>The options, to chain calls.</returns>
    ISectionStoreConfigurationOptions Add<TValue>(string key, TValue? value, JsonTypeInfo<TValue> typeInfo);

    /// <summary>
    /// Add a section from the existing configuration to be persisted.
    /// </summary>
    /// <remarks>The section is bound and serialized with reflection, which trimming and native AOT do not support: use <see cref="AddFromConfiguration{TValue}(string, Func{IConfigurationSection, TValue}, JsonTypeInfo{TValue})"/> there.</remarks>
    /// <typeparam name="TValue">The type of the value in the existing configuration</typeparam>
    /// <param name="key">the name of the section</param>
    /// <returns></returns>
    [RequiresUnreferencedCode("The section is bound and serialized with reflection. Use AddFromConfiguration with a binding function, e.g. s => s.Get<MyOptions>(), and a JsonTypeInfo<TValue>, so both are generated in your application.")]
    [RequiresDynamicCode("The section is bound and serialized with reflection. Use AddFromConfiguration with a binding function, e.g. s => s.Get<MyOptions>(), and a JsonTypeInfo<TValue>, so both are generated in your application.")]
    ISectionStoreConfigurationOptions Add<TValue>(string key);

    /// <summary>
    /// Add a section from the existing configuration to be persisted, bound by <paramref name="bind"/>.
    /// Because the binding is written in the application, where <typeparamref name="TValue"/> is known, the configuration
    /// binding generator of the application generates it.
    /// </summary>
    /// <remarks>The value is serialized with reflection, which trimming and native AOT do not support: use <see cref="AddFromConfiguration{TValue}(string, Func{IConfigurationSection, TValue}, JsonTypeInfo{TValue})"/> there.</remarks>
    /// <typeparam name="TValue">The type of the value in the existing configuration</typeparam>
    /// <param name="key">the name of the section</param>
    /// <param name="bind">The function that reads the section, typically <c>section =&gt; section.Get&lt;MyOptions&gt;()</c>.</param>
    /// <returns>The options, to chain calls.</returns>
    [RequiresUnreferencedCode("The value is serialized with reflection. Use the overload taking a JsonTypeInfo<TValue>, generated by a JsonSerializerContext in your application.")]
    [RequiresDynamicCode("The value is serialized with reflection. Use the overload taking a JsonTypeInfo<TValue>, generated by a JsonSerializerContext in your application.")]
    ISectionStoreConfigurationOptions AddFromConfiguration<TValue>(string key, Func<IConfigurationSection, TValue?> bind);

    /// <summary>
    /// Add a section from the existing configuration to be persisted, bound by <paramref name="bind"/> and serialized with <paramref name="typeInfo"/>.
    /// Because both are generated in the application, where <typeparamref name="TValue"/> is known (the binding by the configuration
    /// binding generator, the metadata by a <c>JsonSerializerContext</c>), it works with trimming and native AOT.
    /// </summary>
    /// <typeparam name="TValue">The type of the value in the existing configuration</typeparam>
    /// <param name="key">the name of the section</param>
    /// <param name="bind">The function that reads the section, typically <c>section =&gt; section.Get&lt;MyOptions&gt;()</c>.</param>
    /// <param name="typeInfo">The Json metadata of <typeparamref name="TValue"/>, typically <c>MyJsonContext.Default.MyOptions</c>.</param>
    /// <returns>The options, to chain calls.</returns>
    ISectionStoreConfigurationOptions AddFromConfiguration<TValue>(string key, Func<IConfigurationSection, TValue?> bind, JsonTypeInfo<TValue> typeInfo);
}
