using System.Diagnostics.CodeAnalysis;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization.Metadata;

namespace Arc4u.Configuration.Store.Internals;

/// <summary>
/// We need a value holder for holding the value to be serialized because some of those values
/// can be primitive types, which are not a Json object. By wrapping values in an object with a single
/// <see cref="ValueHolder.ValuePropertyName"/> property, we avoid having to check for that special case.
/// </summary>
/// <typeparam name="TValue">The type of the value.</typeparam>
sealed class ValueHolder<TValue>(TValue? value, JsonTypeInfo<TValue> typeInfo) : IValueHolder
{
    public string Serialize() => ValueHolder.Serialize(value, typeInfo);
}

static class ValueHolder
{
    /// <summary>
    /// The name of the property holding the value in the persisted Json.
    /// </summary>
    public const string ValuePropertyName = "Value";

    private const string ReflectionMessage = "The value is serialized with reflection. Use the overload taking a JsonTypeInfo<TValue>, generated by a JsonSerializerContext in your application.";

    public static ValueHolder<TValue> Create<TValue>(TValue? value, JsonTypeInfo<TValue> typeInfo) => new(value, typeInfo);

    /// <summary>
    /// The metadata built with reflection, with the default options that were always used to persist the values.
    /// </summary>
    [RequiresUnreferencedCode(ReflectionMessage)]
    [RequiresDynamicCode(ReflectionMessage)]
    public static JsonTypeInfo<TValue> GetReflectionTypeInfo<TValue>()
    {
        return (JsonTypeInfo<TValue>)JsonSerializerOptions.Default.GetTypeInfo(typeof(TValue));
    }

    public static string Serialize<TValue>(TValue? value, JsonTypeInfo<TValue> typeInfo)
    {
        ArgumentNullException.ThrowIfNull(typeInfo);

        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream))
        {
            writer.WriteStartObject();
            writer.WritePropertyName(ValuePropertyName);
            JsonSerializer.Serialize(writer, value!, typeInfo);
            writer.WriteEndObject();
        }

        return Encoding.UTF8.GetString(stream.GetBuffer(), 0, (int)stream.Length);
    }

    public static TValue? Deserialize<TValue>(string json, JsonTypeInfo<TValue> typeInfo)
    {
        ArgumentNullException.ThrowIfNull(typeInfo);

        using var document = JsonDocument.Parse(json);

        return document.RootElement.TryGetProperty(ValuePropertyName, out var element) ? element.Deserialize(typeInfo) : default;
    }
}
