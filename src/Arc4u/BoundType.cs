namespace Arc4u;

/// <summary>
/// Specifies the possible types of a <see cref="Bound&lt;T&gt;"/>.
/// </summary>
public enum BoundType
{
    /// <summary>
    /// Indicates a lower <see cref="Bound&lt;T&gt;"/>.
    /// </summary>
    Lower = 0,
    /// <summary>
    /// Indicates an upper <see cref="Bound&lt;T&gt;"/>.
    /// </summary>
    Upper = 1,
}
